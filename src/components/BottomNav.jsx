// Ordre et correspondance des 5 onglets
const TABS = [
  { id: 'home', labelKey: 'nav.home' },
  { id: 'closing', labelKey: 'nav.closing' },
  { id: 'menu', labelKey: 'nav.menu' },
  { id: 'expenses', labelKey: 'nav.expenses' },
  { id: 'settings', labelKey: 'nav.settings' },
]

export default function BottomNav({ activeTab, onTabChange }) {
  const { t } = useI18n()

  return (
    <nav className="bottom-nav" aria-label="Navigation principale">
      {TABS.map((tab) => {
        const isActive = activeTab === tab.id
        return (
          <button
            key={tab.id}
            type="button"
            className={`nav-item ${isActive ? 'nav-item--active' : ''}`}
            onClick={() => onTabChange(tab.id)}
            aria-current={isActive ? 'page' : undefined}
            aria-label={t(tab.labelKey)}
          >
            <span className="nav-icon">{icons[tab.id]}</span>
            <span className="nav-label">{t(tab.labelKey)}</span>
          </button>
        )
      })}
    </nav>
  )
}